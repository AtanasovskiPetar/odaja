// Builds Odaja's companion as one file that runs without Bun or Node:
//
//   bun run package:server                     → build/odaja for this machine
//   bun run package:server bun-darwin-x64      → for another platform (Bun target name)
//
// The program carries the built app (dist/), the format docs and the sample
// flat inside itself; it unpacks them on first start (server/appFiles.ts).
// `odaja` serves the app, `odaja mcp` is the MCP server. Release files for
// every platform: scripts/release.ts.
import { $ } from "bun";
import { createHash } from "node:crypto";
import fs from "node:fs/promises";
import path from "node:path";

// What the program carries, relative to the repo.
async function appFiles(): Promise<string[]> {
  const walk = async (dir: string): Promise<string[]> => {
    const out: string[] = [];
    for (const e of await fs.readdir(dir, { withFileTypes: true })) {
      const rel = `${dir}/${e.name}`;
      // Chats saved while developing stay behind.
      if (e.name === ".odaja" || e.name === ".DS_Store") continue;
      if (e.isDirectory()) out.push(...(await walk(rel)));
      else out.push(rel);
    }
    return out;
  };
  return [...(await walk("dist")), "docs/project-format.md", ...(await walk("examples/sample-flat"))].sort();
}

// Compiles the companion for `target` (this machine if none) to `outfile`.
// `bun run build` must have run.
export async function compileOdaja(target: string | undefined, outfile: string): Promise<void> {
  const files = await appFiles();
  const hash = createHash("sha256");
  for (const f of files) hash.update(f).update(await fs.readFile(f));
  const { version } = JSON.parse(await fs.readFile("package.json", "utf8"));
  // An entry that embeds every file, then starts the server.
  const dir = path.resolve("build/.embed");
  await fs.rm(dir, { recursive: true, force: true });
  await fs.mkdir(dir, { recursive: true });
  const spec = (f: string) => JSON.stringify(path.relative(dir, path.resolve(f)).split(path.sep).join("/"));
  const entry = [
    "// Generated by scripts/package-server.ts.",
    ...files.map((f, i) => `import f${i} from ${spec(f)} with { type: "file" };`),
    `(globalThis as { __ODAJA_EMBEDDED__?: unknown }).__ODAJA_EMBEDDED__ = {`,
    `  version: ${JSON.stringify(`${version}-${hash.digest("hex").slice(0, 10)}`)},`,
    `  files: [${files.map((f, i) => `[${JSON.stringify(f)}, f${i}]`).join(", ")}],`,
    "};",
    `await import(${spec("server/main.ts")});`,
    "",
  ].join("\n");
  await fs.writeFile(path.join(dir, "entry.ts"), entry);
  await $`bun build --compile --minify --sourcemap ${target ? [`--target=${target}`] : []} ${path.join(dir, "entry.ts")} --outfile ${outfile}`.quiet();
  await fs.rm(dir, { recursive: true, force: true });
  // The source map is built into the program already.
  await fs.rm(`${outfile}.map`, { force: true });
  await fs.rm(path.join(path.dirname(outfile), "entry.js.map"), { force: true });
}

if (import.meta.main) {
  const target = process.argv[2];
  const out = path.resolve("build");
  await fs.rm(out, { recursive: true, force: true });
  await $`bun run build`;
  const binary = path.join(out, target?.includes("windows") ? "odaja.exe" : "odaja");
  await compileOdaja(target, binary);
  const size = (await fs.stat(binary)).size / 1024 / 1024;
  console.log(`\nBuilt ${path.relative(".", binary)} (${size.toFixed(0)} MB)`);
}
